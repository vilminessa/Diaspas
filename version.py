"""Версия приложения - два значения с разными ролями.

``__version__`` - числовая версия (X.Y.Z или X.Y.Z.N): её читает
``diaspas.spec`` (VersionInfo exe) и тесты.

``BUILD_LABEL`` - подпись для интерфейса и журнала (полный тег сборки:
``v0.1.2`` или ``b0.1.2``); пустая строка = собрано не из тега, и окно
показывает ``unreleased``.

Коммитов с бампом версии не нужно: workflow ``release``/``beta`` перед
сборкой exe зовёт :command:`tools/stamp_version.py <тег>`, который вписывает
оба значения в одноразовое рабочее дерево CI - в git ничего не попадает.
Локально та же утилита пригодится перед ручной сборкой из тега.

Процесс выпуска:
  бета:  коммит в dev -> тег ``b<номер>`` -> сборка из dev, Pre-release;
  финал: main подтягивается до dev -> тег ``v<номер>`` -> сборка из main.

Максимум четыре компонента версии: Windows VersionInfo больше не принимает,
поэтому «промежуточность» несёт префикс ``b``, а не пятый разряд.
"""

__version__ = "0.1.1"
# Подпись интерфейса; заполняется tools/stamp_version.py при сборке из тега,
# иначе окно показывает "unreleased".
BUILD_LABEL = ""


def label() -> str:
    """Что показать в интерфейсе: тег сборки или «unreleased»."""
    return BUILD_LABEL or "unreleased"


def is_beta() -> bool:
    """Бета-полоса: префикс b в теге сборки."""
    return BUILD_LABEL.startswith("b")
